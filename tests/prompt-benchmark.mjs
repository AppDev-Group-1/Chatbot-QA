const failures = [];
let promptCount = 0;

for (const group of definitionGroups) {
  let passed = 0;
  for (const prompt of group.prompts) {
    promptCount++;
    const result = answer(prompt);
    if (result.status === "correct" && result.item.name === group.name) {
      passed++;
    } else {
      const nearest = match(preprocess(prompt));
      failures.push({
        expected: group.name,
        prompt,
        status: result.status,
        matched: result.item?.name ?? null,
        score: Number(result.score.toFixed(2)),
        nearest: nearest.item?.name ?? null,
        nearestScore: Number(nearest.score.toFixed(2)),
        runnerUp: nearest.runnerUpItem?.name ?? null,
        runnerUpScore: Number(nearest.runnerUp.toFixed(2))
      });
    }
  }
  console.log(`${group.name}: ${passed}/${group.prompts.length}`);
}

